"""Generate the Marquee adaptive icon (Android vectors) + an SVG/PNG preview
from one shape list, so the preview and the shipped icon always match.
Viewport is the adaptive-icon 108x108 grid; keep art inside the 66dp safe zone.
"""
import sys, os

out_repo = sys.argv[1]
out_prev = sys.argv[2]

BG_TOP, BG_BOTTOM = "#C0182A", "#3A0710"

# Spines: (x, y_top, width, color, alpha). Baseline y=72.
BASE = 72.0
spines = [
    (27.0, 46.0, 3.6, "#FFFFFF", 0.55),
    (31.6, 41.0, 4.2, "#1A0A0C", 0.85),
    (36.8, 44.0, 3.4, "#FFFFFF", 0.85),
    # cover sits 41..67
    (68.6, 43.0, 3.4, "#FFFFFF", 0.85),
    (72.8, 40.0, 4.2, "#1A0A0C", 0.85),
    (77.8, 46.0, 3.6, "#FFFFFF", 0.55),
]
# Featured cover
CX0, CY0, CX1, CY1, R, STROKE = 41.5, 33.0, 66.5, 72.0, 2.0, 2.4
# Play triangle inside the cover
cx, cy = (CX0 + CX1) / 2 + 0.8, (CY0 + CY1) / 2
tri = [(cx - 4.6, cy - 6.2), (cx - 4.6, cy + 6.2), (cx + 6.0, cy)]


def rrect(x0, y0, x1, y1, r):
    return (f"M{x0+r},{y0} L{x1-r},{y0} Q{x1},{y0} {x1},{y0+r} L{x1},{y1-r} "
            f"Q{x1},{y1} {x1-r},{y1} L{x0+r},{y1} Q{x0},{y1} {x0},{y1-r} "
            f"L{x0},{y0+r} Q{x0},{y0} {x0+r},{y0} Z")


def spine_path(x, y, w):
    return rrect(x, y, x + w, BASE, 0.6)


tri_path = "M{:.2f},{:.2f} L{:.2f},{:.2f} L{:.2f},{:.2f} Z".format(*[c for p in tri for c in p])
cover_outer = rrect(CX0, CY0, CX1, CY1, R)
s = STROKE
cover_inner = rrect(CX0 + s, CY0 + s, CX1 - s, CY1 - s, max(R - s / 2, 0.4))

# ---------- Android vectors ----------
bg_xml = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Marquee icon background: a deep marquee-red gradient. Generated by
     tools/make_icon.py — edit the script, not this file. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient
                android:type="linear"
                android:startX="20" android:startY="0"
                android:endX="88" android:endY="108">
                <item android:offset="0" android:color="#FF{BG_TOP[1:]}" />
                <item android:offset="1" android:color="#FF{BG_BOTTOM[1:]}" />
            </gradient>
        </aapt:attr>
    </path>
</vector>
'''


def fg_xml(mono=False):
    parts = []
    for x, y, w, col, a in spines:
        c = "#FFFFFFFF" if mono else "#FF" + col[1:]
        alpha = a if not mono else (1.0 if col == "#FFFFFF" else 0.45)
        parts.append(f'    <path android:pathData="{spine_path(x, y, w)}"\n'
                     f'        android:fillColor="{c}" android:fillAlpha="{alpha:.2f}" />')
    # cover: white frame (even-odd ring), dark face, white play
    parts.append(f'    <path android:pathData="{cover_outer} {cover_inner}"\n'
                 f'        android:fillType="evenOdd" android:fillColor="#FFFFFFFF" />')
    if not mono:
        parts.append(f'    <path android:pathData="{cover_inner}" android:fillColor="#FF14080A" />')
    parts.append(f'    <path android:pathData="{tri_path}" android:fillColor="#FFFFFFFF" />')
    body = "\n".join(parts)
    note = "monochrome (themed icon) layer" if mono else "foreground"
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Marquee icon {note}: a shelf of game spines with one cover pulled
     forward. Generated by tools/make_icon.py — edit the script, not this file. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
{body}
</vector>
'''


res = os.path.join(out_repo, "app/src/main/res")
os.makedirs(os.path.join(res, "drawable"), exist_ok=True)
open(os.path.join(res, "drawable/ic_launcher_background.xml"), "w").write(bg_xml)
open(os.path.join(res, "drawable/ic_launcher_foreground.xml"), "w").write(fg_xml())
open(os.path.join(res, "drawable/ic_launcher_monochrome.xml"), "w").write(fg_xml(mono=True))

# ---------- SVG preview (circle-masked, like a launcher) ----------
sp = "\n".join(f'<path d="{spine_path(x, y, w)}" fill="{c}" fill-opacity="{a}"/>' for x, y, w, c, a in spines)
svg = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108" width="512" height="512">
<defs>
 <linearGradient id="g" x1="20" y1="0" x2="88" y2="108" gradientUnits="userSpaceOnUse">
  <stop offset="0" stop-color="{BG_TOP}"/><stop offset="1" stop-color="{BG_BOTTOM}"/></linearGradient>
 <clipPath id="m"><circle cx="54" cy="54" r="36"/></clipPath>
</defs>
<g clip-path="url(#m)" transform="translate(-18 -18) scale(1.3333)">
<rect width="108" height="108" fill="url(#g)"/>
{sp}
<path d="{cover_outer} {cover_inner}" fill-rule="evenodd" fill="#fff"/>
<path d="{cover_inner}" fill="#14080A"/>
<path d="{tri_path}" fill="#fff"/>
</g></svg>'''
# The translate/scale maps the visible 72dp circle (18..90) onto the full canvas.
open(out_prev, "w").write(svg)
print("ok")
